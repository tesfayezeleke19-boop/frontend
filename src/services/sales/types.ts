/**
 * NexERP — Sales data model.
 *
 * These types are the single source of truth for the Sales order shape and
 * lifecycle. UI pages import them through the service layer (src/services/sales)
 * instead of defining their own copies, so swapping the temporary local
 * repository for the PHP REST API later will not require UI changes.
 */

/**
 * Internal order status values. These are the application's business statuses —
 * never use display strings for logic.
 *
 * Lifecycle:
 *   DRAFT → PENDING_FINANCE_REVIEW → FINANCE_APPROVED → PAYMENT_CONFIRMED
 *   PENDING_FINANCE_REVIEW → REJECTED (may be edited/resubmitted by Sales)
 */
export const ORDER_STATUS = {
  DRAFT: "DRAFT",
  PENDING_FINANCE_REVIEW: "PENDING_FINANCE_REVIEW",
  FINANCE_APPROVED: "FINANCE_APPROVED",
  REJECTED: "REJECTED",
  PAYMENT_CONFIRMED: "PAYMENT_CONFIRMED",
} as const;

export type OrderStatus = (typeof ORDER_STATUS)[keyof typeof ORDER_STATUS];

/** Human-readable labels for the UI. */
export const ORDER_STATUS_LABELS: Record<OrderStatus, string> = {
  DRAFT: "Draft",
  PENDING_FINANCE_REVIEW: "Pending Finance Review",
  FINANCE_APPROVED: "Finance Approved",
  REJECTED: "Rejected",
  PAYMENT_CONFIRMED: "Payment Confirmed",
};

/** Status → badge styling used across the Sales pages. */
export const ORDER_STATUS_UI: Record<
  OrderStatus,
  { label: string; className: string }
> = {
  DRAFT: { label: "Draft", className: "erp-badge-draft" },
  PENDING_FINANCE_REVIEW: {
    label: "Pending Finance Review",
    className: "erp-badge-pending",
  },
  FINANCE_APPROVED: {
    label: "Finance Approved",
    className: "erp-badge-approved",
  },
  REJECTED: { label: "Rejected", className: "erp-badge-rejected" },
  PAYMENT_CONFIRMED: {
    label: "Payment Confirmed",
    className: "erp-badge-payment",
  },
};

/** Orders Sales can still edit and resubmit. */
export function isEditableStatus(status: OrderStatus): boolean {
  return (
    status === ORDER_STATUS.DRAFT || status === ORDER_STATUS.REJECTED
  );
}

/** Valid aggregate type codes — matches the royalty spreadsheet convention. */
export const AGGREGATE_TYPES = ["00", "01", "02"] as const;
export type AggregateType = (typeof AGGREGATE_TYPES)[number];

/** Human-readable labels for aggregate codes. */
export const AGGREGATE_LABELS: Record<AggregateType, string> = {
  "00": "00",
  "01": "01",
  "02": "02",
};

/** Fields entered by Sales when creating or editing an order. */
export interface OrderInput {
  customerName: string;
  tin: string;
  reffNo: string;
  aggregate: AggregateType;
  quantity: number;
  unit: string;
  unitPrice: number;
  bank: string;
  senderName: string;
  transactionNumber: string;
  remark?: string;
}

/** A sales transaction. */
export interface SalesOrder extends OrderInput {
  id: string;
  orderNumber: string; // e.g. ORDER-0001, generated by the repository
  /** VAT-exclusive total: unitPrice × quantity */
  totalPriceExclVat: number;
  /** VAT-inclusive total: (unitPrice × 1.15) × quantity */
  totalPriceInclVat: number;
  status: OrderStatus;
  orderDate: number;
  createdAt: number;
  updatedAt: number;
  submittedAt?: number;
  financeReviewedAt?: number;
  approvedAt?: number;
  rejectedAt?: number;
  paymentConfirmedAt?: number;
  rejectionReason?: string;
  createdBy?: string;
  submittedBy?: string;
  financeReviewedBy?: string;
  approvedBy?: string;
  paymentConfirmedBy?: string;
}

/** Aggregations used by the Sales dashboard. Derived from the order collection. */
export interface SalesSummary {
  totalOrders: number;
  totalRevenue: number;
  draft: number;
  pendingReview: number;
  approved: number;
  rejected: number;
  paymentConfirmed: number;
  byAggregate: { name: string; value: number }[];
  byMonth: { name: string; value: number }[];
  recent: SalesOrder[];
}

export const REPORT_STATUS = {
  DRAFT: "DRAFT",
  FINAL: "FINAL",
} as const;

/**
 * A standard Sales Report groups exactly this many approved transactions.
 * The business requirement is 50 per report.
 */
export const REPORT_TRANSACTION_LIMIT = 50;

export type ReportStatus = (typeof REPORT_STATUS)[keyof typeof REPORT_STATUS];

/** A sales report grouping approved transactions (50-transaction concept). */
export interface SalesReport {
  id: string;
  reportNumber: string; // e.g. SALES-REPORT-0001
  orderIds: string[];
  transactionCount: number;
  totalQuantity: number;
  totalAmount: number;
  status: ReportStatus;
  createdBy?: string;
  createdAt: number;
}

/** A sales report with the full orders embedded. */
export interface SalesReportDetail extends SalesReport {
  orders: SalesOrder[];
}
